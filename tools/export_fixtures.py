#!/usr/bin/env python3
"""Export the shared protocol knowledge for the Dance Party repository.

Govee-Bluetooth owns the model classification (``fixtures/govee-models.json``)
and the frame builders (``protocol.py``). Dance Party must not re-derive
either, so this script writes two plain-C headers it can vendor:

* ``govee_models_gen.h``: the RGBIC / dreamcolor / RGBWW / legacy / secret
  tables as ``static const char* const`` arrays, from the JSON;
* ``govee_frame_vectors_gen.h``: ``{name, hex}`` pairs produced by
  ``protocol.py`` for every frame the two C implementations also build, so
  their host tests can compare byte for byte.

    python3 tools/export_fixtures.py --out-dir /path/to/govee-dance-party/generated

Each header records the generator, the fixture schema and the git commit it
came from. Regenerate and copy both when the tables change; the Dance Party
host tests fail if its tables drift from the vendored header.
"""

from __future__ import annotations

import argparse
import importlib
import json
import subprocess
import sys
import types
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKAGE_DIR = REPO_ROOT / "custom_components" / "govee_bluetooth"
FIXTURE = REPO_ROOT / "fixtures" / "govee-models.json"


def load_protocol():  # type: ignore[no-untyped-def]
    for name, path in (
        ("custom_components", REPO_ROOT / "custom_components"),
        ("custom_components.govee_bluetooth", PACKAGE_DIR),
    ):
        if name not in sys.modules:
            stub = types.ModuleType(name)
            stub.__path__ = [str(path)]  # type: ignore[attr-defined]
            sys.modules[name] = stub
    return importlib.import_module("custom_components.govee_bluetooth.protocol")


def git_sha() -> str:
    try:
        return subprocess.run(
            ["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True, timeout=5,
        ).stdout.strip()  # fmt: skip
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def _c_array(name: str, values: list[str]) -> str:
    rows = []
    for i in range(0, len(values), 8):
        rows.append("    " + ", ".join(f'"{v}"' for v in values[i : i + 8]) + ",")
    return f"static const char* const {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def models_header(fixture: dict, sha: str) -> str:  # type: ignore[type-arg]
    models = fixture["models"]

    def with_dialect(dialect: str, *, dance_party: bool = True) -> list[str]:
        out = []
        for sku, row in models.items():
            d = row.get("dance_party_dialect", row["dialect"]) if dance_party else row["dialect"]
            if d == dialect:
                out.append(sku)
        return sorted(out)

    rgbic = sorted(
        set(with_dialect("rgbic"))
        | set(fixture["dreamcolor_pact_models"]) & set(with_dialect("rgbic"))
    )
    dreamcolor = sorted(fixture["dreamcolor_pact_models"])
    rgbww = with_dialect("rgbww")
    legacy = sorted(
        sku for sku in with_dialect("legacy") if sku not in fixture["dreamcolor_pact_models"]
    )
    secret = sorted(fixture["secret_family_models"])
    return (
        "/* Generated by tools/export_fixtures.py in Mezzle/govee-bluetooth from\n"
        f" * fixtures/govee-models.json ({fixture['schema']}) at commit {sha}.\n"
        " * Do not edit: change the JSON there and regenerate. Shared by\n"
        " * govee_protocol.c (Flipper) and govee_frames.h (ESP32). */\n"
        "#pragma once\n\n"
        '#define GOVEE_MODELS_FIXTURE_SCHEMA "' + fixture["schema"] + '"\n'
        f'#define GOVEE_MODELS_FIXTURE_COMMIT "{sha}"\n\n'
        "/* 0x15 on current firmware (RGBIC strips, TV backlights, bars, panels). */\n"
        + _c_array("GOVEE_GEN_RGBIC_MODELS", rgbic)
        + "\n/* The advertised pact decides: type 1 -> 0x0B, type 2 / 10 -> 0x15. */\n"
        + _c_array("GOVEE_GEN_DREAMCOLOR_MODELS", dreamcolor)
        + "\n/* 0x0D on hardware (H6181 fw 2.03.11). */\n"
        + _c_array("GOVEE_GEN_RGBWW_MODELS", rgbww)
        + "\n/* Telink-era 0x02 strips as tabled by the HA integration. */\n"
        + _c_array("GOVEE_GEN_LEGACY_MODELS", legacy)
        + "\n/* Families tagged secret_key_pairing in the decompiled app. */\n"
        + _c_array("GOVEE_GEN_SECRET_MODELS", secret)
    )


def frame_vectors(protocol) -> list[tuple[str, str]]:  # type: ignore[no-untyped-def]
    vectors = [
        ("power_on", protocol.power_frame(True)),
        ("power_off", protocol.power_frame(False)),
        ("brightness_legacy_255", protocol.brightness_frame(255, 255)),
        ("brightness_legacy_128", protocol.brightness_frame(128, 255)),
        ("brightness_percent_100", protocol.brightness_frame(255, 100)),
        ("brightness_percent_50", protocol.brightness_frame(128, 100)),
        ("rgb_legacy_123456", protocol.rgb_frame(0x12, 0x34, 0x56)),
        ("rgb_rgbww_123456", protocol.rgb_frame(0x12, 0x34, 0x56, submode=0x0D)),
        ("rgb_rgbic_123456_15seg", protocol.rgb_frame(0x12, 0x34, 0x56, submode=0x15)),
        ("rgb_dreamcolor_123456_15seg", protocol.rgb_frame(0x12, 0x34, 0x56, submode=0x0B)),
        ("ct_legacy_2700", protocol.color_temp_frame(2700)),
        ("ct_rgbww_2700", protocol.color_temp_frame(2700, submode=0x0D)),
        ("ct_rgbic_2700", protocol.color_temp_frame(2700, submode=0x15)),
        ("scene_blinking", protocol.scene_frame(0x08)),
        ("read_power", protocol.power_query_frame()),
        ("read_brightness", protocol.brightness_query_frame()),
        ("read_mode", protocol.mode_query_frame()),
        ("read_firmware", protocol.version_query_frame()),
        ("read_hardware", protocol.hardware_query_frame()),
        ("read_ic_count", protocol.ic_count_query_frame()),
        ("read_light_count", protocol.light_count_query_frame()),
        ("read_secret", protocol.secret_query_frame()),
        ("read_segment_colors_1", protocol.segment_colors_query_frame(1)),
    ]
    return [(name, frame.hex()) for name, frame in vectors]


def vectors_header(vectors: list[tuple[str, str]], sha: str) -> str:
    rows = "\n".join(f'    {{"{name}", "{hex_}"}},' for name, hex_ in vectors)
    return (
        "/* Generated by tools/export_fixtures.py in Mezzle/govee-bluetooth from\n"
        f" * custom_components/govee_bluetooth/protocol.py at commit {sha}.\n"
        " * Do not edit. Dance Party's host tests compare its builders to these. */\n"
        "#pragma once\n\n"
        f'#define GOVEE_FRAME_VECTORS_COMMIT "{sha}"\n\n'
        "typedef struct {\n    const char* name;\n    const char* hex;\n} GoveeFrameVector;\n\n"
        "static const GoveeFrameVector GOVEE_FRAME_VECTORS[] = {\n" + rows + "\n};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--fixture", type=Path, default=FIXTURE)
    args = parser.parse_args(argv)
    fixture = json.loads(args.fixture.read_text(encoding="utf-8"))
    protocol = load_protocol()
    sha = git_sha()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "govee_models_gen.h").write_text(models_header(fixture, sha), encoding="utf-8")
    (args.out_dir / "govee_frame_vectors_gen.h").write_text(
        vectors_header(frame_vectors(protocol), sha), encoding="utf-8"
    )
    print(
        f"wrote {args.out_dir / 'govee_models_gen.h'} and govee_frame_vectors_gen.h (commit {sha})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
